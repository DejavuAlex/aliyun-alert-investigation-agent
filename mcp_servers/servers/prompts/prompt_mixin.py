
class PromptMixin:
    def __init__(self):
        self.mandatory_rules = \
             """
            ✅ 必须遵守：
            - 调查时首先搜索工具中的调查模版prompt，其优先级最高，如果实在没有，则自行分析
            - 任何分析步骤中，需要外部数据支持的时候，优先搜索是否有相关工具可用
            - 仅当实际调用了工具时才记录工具信息
            - 工具调用格式：工具名称 | 状态：成功/失败 | 失败原因（如失败）
            - 无工具调用的步骤只需记录分析结果，不得虚构工具调用
            - 工具调用失败时必须说明具体原因及其对分析的影响
            - 工具调用成功时，在显示状态中加入✅
            - 工具调用成功但无数据返回，在显示状态中加入⚠️ 并说明无数据原因
            - 工具调用失败时，在显示状态中加入❌
            - 任一工具失败时，必须说明失败原因与对结论的影响，并给出替代调查路径（例如改用不同时间窗/不同过滤条件/补充资产侧日志）
            - 所有判断必须基于告警中提供的或可通过工具获取的真实数据
            - 不得假设存在未明确提供的安全产品（如未启用云防火墙则不可引用其日志）
            - 调用和阿里云相关的工具时候:
                - 遇到API流控时采用节流与重试，而不是跳过
                - 常常需要指定region_id, access_key_id才能进行查询，如果未明确指定，则默认查询所有access_key_id下的所有region_id的资源
                - 当接口返回 next_token 时，必须自动分页迭代，直至找到目标或数据耗尽。
            - 遇到任何IP如果是外网IP，都需要执行本地工具库中IP调查相关的prompt
            """
        self.constraints = \
            """
            ⛔ 不允许：
            - 在未调用工具的步骤中编造工具名称或状态
            - 使用“可能”“大概”等模糊状态描述
            - 忽略工具失败对结论的影响
            - 引用未在环境中部署的安全能力（如未安装云安全中心Agent则不可获取进程快照）
            ✅ 必须做到：
            - 如实反映每一步是否依赖工具及结果
            - 工具成功时清晰列出获取的关键信息
            - 工具失败时说明限制并尝试基于已有信息推断
            - 保持调查逻辑的可追溯性和真实性
            """